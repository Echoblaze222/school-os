// scripts/generate-sw-precache.js
// Run automatically after `next build` (see package.json "postbuild" script
// below). Reads Next.js's own build manifest - which only exists after a
// real build, since it contains the actual hashed chunk filenames - and
// writes public/sw-precache-manifest.js, which sw.js loads via
// importScripts() to know exactly which JS/CSS files to cache on install.
//
// This solves the "first visit must be online" gap in the runtime-caching
// service worker: instead of only caching pages/chunks opportunistically as
// a user happens to visit them, the critical first-load routes (splash,
// login, select-school, offline) get their real chunks cached immediately
// on install, so even a first-ever visit that goes offline mid-session has
// what it needs.
//
// Usage: node scripts/generate-sw-precache.js
// (Runs automatically via the "postbuild" npm script - see below.)

const fs = require('fs')
const path = require('path')

// Routes whose JS/CSS chunks should be precached on install. Keep this
// list small and deliberate - these are the screens someone needs before
// they're authenticated / before there's any app data to show, i.e. the
// ones that must work even on a first, possibly-offline-mid-load visit.
// Deliberately NOT including role dashboards - those are large, per-role,
// and only matter after login (by which point the runtime cache has
// already picked them up from normal navigation).
const CRITICAL_ROUTES = ['/', '/splash', '/login', '/select-school', '/offline']

const NEXT_DIR = path.join(process.cwd(), '.next')
const OUTPUT_PATH = path.join(process.cwd(), 'public', 'sw-precache-manifest.js')

function loadManifest() {
  // App Router (Next 13+): .next/app-build-manifest.json
  const appManifestPath = path.join(NEXT_DIR, 'app-build-manifest.json')
  if (fs.existsSync(appManifestPath)) {
    return { manifest: JSON.parse(fs.readFileSync(appManifestPath, 'utf8')), kind: 'app' }
  }
  // Fallback: Pages Router / older manifest shape
  const buildManifestPath = path.join(NEXT_DIR, 'build-manifest.json')
  if (fs.existsSync(buildManifestPath)) {
    return { manifest: JSON.parse(fs.readFileSync(buildManifestPath, 'utf8')), kind: 'pages' }
  }
  return null
}

function routeToAppManifestKey(route) {
  // app-build-manifest.json keys look like "/login/page" for src/app/login/page.tsx,
  // and "/page" for the root src/app/page.tsx.
  if (route === '/') return '/page'
  return `${route}/page`
}

function main() {
  const loaded = loadManifest()
  if (!loaded) {
    console.warn(
      '[generate-sw-precache] No .next build manifest found - did `next build` run first? ' +
      'Skipping precache manifest generation; sw.js will fall back to runtime-only caching.'
    )
    // Write an empty manifest so sw.js's importScripts() doesn't 404.
    fs.writeFileSync(OUTPUT_PATH, 'self.__PRECACHE_URLS = [];\n')
    return
  }

  const { manifest, kind } = loaded
  const urls = new Set()

  if (kind === 'app') {
    for (const route of CRITICAL_ROUTES) {
      const key = routeToAppManifestKey(route)
      const files = manifest.pages?.[key]
      if (!files) {
        console.warn(`[generate-sw-precache] No manifest entry for route "${route}" (looked up key "${key}") - skipping.`)
        continue
      }
      for (const file of files) {
        if (file.endsWith('.js') || file.endsWith('.css')) urls.add(`/_next/${file}`)
      }
    }
  } else {
    // Pages Router fallback: build-manifest.json keys are the route paths directly.
    for (const route of CRITICAL_ROUTES) {
      const files = manifest.pages?.[route]
      if (!files) continue
      for (const file of files) {
        if (file.endsWith('.js') || file.endsWith('.css')) urls.add(`/_next/${file}`)
      }
    }
  }

  const urlList = [...urls]
  fs.writeFileSync(
    OUTPUT_PATH,
    `// AUTO-GENERATED by scripts/generate-sw-precache.js - do not edit by hand.\n` +
    `// Regenerated on every \`next build\` via the "postbuild" script.\n` +
    `self.__PRECACHE_URLS = ${JSON.stringify(urlList, null, 2)};\n`
  )

  console.log(`[generate-sw-precache] Wrote ${urlList.length} precache URLs to public/sw-precache-manifest.js`)
}

main()
